"""Writes jitnodes/__init__.pyi, the type stubs of what a script sees (the handles), from the generated jitnodes/_core.pyi.

    python genHandleStubs.py <_core.pyi> <__init__.pyi>

The handles forward to the engine's classes, so their methods are the engine's with the translations pyHandles.cpp makes:
node ids become Node handles, and a Node or Network handle is accepted where the engine takes one.
"""

import ast
import sys

# The names pyHandles.cpp translates (singleNodeResults, listNodeResults, setNodeResults) and the ids it unwraps.
SINGLE_RESULTS = {"add_node": "Node", "add_node_with_id": "Node", "find_node": "Node | None", "input_of": "Node | None",
                  "display_node": "Node | None"}
LIST_RESULTS = {"node_ids", "consumers_of", "execution_order"}
SET_RESULTS = {"dependents_of"}
NODE_ARGUMENTS = {"id", "to", "from_", "owner"}
NOT_NODE_ARGUMENTS = {("add_node_with_id", "id")}

GEOMETRY_ARRAYS = '''
    def attrib(self, attrib_class: AttribClass, name: str) -> npt.NDArray[Any]: ...
    def point_attrib(self, name: str) -> npt.NDArray[Any]: ...
    def prim_attrib(self, name: str) -> npt.NDArray[Any]: ...
    def attrib_names(self, attrib_class: AttribClass) -> list[str]: ...
    def attrib_type(self, attrib_class: AttribClass, name: str) -> AttribType: ...
    def strings(self, attrib_class: AttribClass, name: str) -> list[str]: ...
    def string_values(self, attrib_class: AttribClass, name: str) -> list[str]: ...
    def render_png(self, path: str, width: int = 0, height: int = 0) -> tuple[int, int]: ...
'''

NETWORK_HANDLE = '''
    valid: bool
    def __init__(self, threads: int = 0) -> None: ...
    def __len__(self) -> int: ...
    def __iter__(self) -> Iterator[Node]: ...
    def __contains__(self, key: Node | str | int) -> bool: ...
    def __getitem__(self, key: Node | str | int) -> Node: ...
    def nodes(self) -> list[Node]: ...
    def node(self, key: Node | str | int) -> Node: ...
'''

NODE_HANDLE = '''
    id: int
    valid: bool
    network: Network
    def __eq__(self, other: object) -> bool: ...
    def __hash__(self) -> int: ...
    def __getitem__(self, name: str) -> Any: ...
    def __setitem__(self, name: str, value: Any) -> None: ...
    def __contains__(self, name: str) -> bool: ...
    def __getattr__(self, name: str) -> Any: ...
    def __setattr__(self, name: str, value: Any) -> None: ...
    def __rshift__(self, target: Node) -> Node: ...
    def connect(self, target: Node, input: int = 0) -> Node: ...
    def disconnect(self, input: int = 0) -> None: ...
'''

HISTORY_HANDLE = '''
    def __init__(self, network: Network, max_states: int = 100) -> None: ...
'''


def expression(text):
    return ast.parse(text, mode="eval").body


def translated(function, owner):
    function = ast.parse(ast.unparse(function)).body[0]
    arguments = function.args.args
    for argument in arguments:
        if owner == "Network" and argument.arg in NODE_ARGUMENTS and (function.name, argument.arg) not in NOT_NODE_ARGUMENTS:
            kind = ast.unparse(argument.annotation) if argument.annotation else ""
            if kind == "int":
                argument.annotation = expression("Node | int")
            elif kind == "list[int]":
                argument.annotation = expression("list[Node | int]")
    if owner == "Network":
        if function.name in SINGLE_RESULTS:
            function.returns = expression(SINGLE_RESULTS[function.name])
        elif function.name in LIST_RESULTS:
            function.returns = expression("list[Node]")
        elif function.name in SET_RESULTS:
            function.returns = expression("set[Node]")
    return function


def class_text(name, core_class, handle_text, skip):
    lines = [f"class {name}:"]
    lines.append(handle_text.strip("\n"))
    for item in core_class.body:
        if isinstance(item, ast.FunctionDef) and item.name not in skip:
            lines.append(textwrap_indent(ast.unparse(translated(item, name)).replace(":\n    ...", ": ...")))
        elif isinstance(item, ast.AnnAssign):
            lines.append("    " + ast.unparse(item))
    return "\n".join(lines) + "\n"


def textwrap_indent(text):
    return "\n".join("    " + line for line in text.splitlines())


def main():
    core = ast.parse(open(sys.argv[1], encoding="utf-8").read())
    classes = {node.name: node for node in core.body if isinstance(node, ast.ClassDef)}

    values = [name for name in classes if name not in ("Network", "Node", "History", "Geometry")]
    out = [
        "# Generated by genHandleStubs.py from _core.pyi - do not edit.",
        "from __future__ import annotations",
        "from typing import Any, Callable, ClassVar, Iterator, overload",
        "",
        "import numpy.typing as npt",
        "",
        "from ._core import " + ", ".join(f"{name} as {name}" for name in values),
        "",
        "class StaleHandleError(ReferenceError): ...",
        "",
    ]

    geometry = class_text("Geometry", classes["Geometry"], "", set())
    out.append(geometry + GEOMETRY_ARRAYS.strip("\n") + "\n")
    out.append(class_text("Network", classes["Network"], NETWORK_HANDLE, {"__init__", "node"}))
    out.append(class_text("Node", classes["Node"], NODE_HANDLE, {"id", "__init__"}))
    out.append(class_text("History", classes["History"], HISTORY_HANDLE, {"__init__"}))

    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(out))


if __name__ == "__main__":
    main()
